#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn packedCourseTablesHoldEveryTableAndPackTheSameEachTime() {
        for (file, tables) in [
            (StoreFile::CourseEventParamsJp, COURSE_EVENT_PARAMS),
            (
                StoreFile::CourseEventParamsGlobal,
                GLOBAL_COURSE_EVENT_PARAM_OVERRIDES,
            ),
        ] {
            let packed: BTreeMap<String, serde_json::Value> =
                serde_json::from_slice(bundled(file)).unwrap();
            assert_eq!(packed.len(), tables.len());
            for (course_id, json) in tables {
                let table: serde_json::Value = serde_json::from_str(json).unwrap();
                assert_eq!(packed[*course_id], table, "{file:?} course {course_id}");
            }
            assert_eq!(bundled(file), packCourseEventParams(tables));
        }
    }
}
